package com.mastek.pulse.ai;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.UUID;

/**
 * ============================================================================
 * INTERN & AI AGENT GUIDE — WHAT IS THIS FILE?
 * ============================================================================
 * File: AiUsageLedgerEntity.java
 * Journey: Supporting Journey C ("Use optional AI drafting or summarization,
 *          review the result, and explicitly choose the next action" -
 *          Proposal Pages 4 & 5).
 *
 * Why it is designed this way:
 *   Page 5 of the proposal specifies an illustrative 4-week pilot workload of
 *   720 AI actions (60 people x 4 weeks x 3 actions; ~1,000 input + 500 output tokens)
 *   and requires: "Alert at 50%, 80%, and 100%; disable optional AI at the cap."
 *   Every bounded AI call logs an immutable row in the `ai_usage_ledger` table so we
 *   can track token usage, audit which content context triggered the call, and
 *   enforce the hard cap deterministically.
 *
 * JPA Annotations Explained for Interns:
 *   - `@Entity`: Marks this class as a persistent JPA entity managed by Hibernate.
 *   - `@Table(name = "ai_usage_ledger")`: Maps this class to the `ai_usage_ledger`
 *     table created by Flyway in `V1__init_schema.sql`.
 *   - `@Id`: Designates `id` as the primary key column of the table.
 *   - `@Column(...)`: Maps each Java field to its corresponding snake_case SQL column
 *     and enforces `NOT NULL` and maximum character length constraints at the ORM layer.
 * ============================================================================
 */
@Entity
@Table(name = "ai_usage_ledger")
public class AiUsageLedgerEntity {

    /**
     * Primary key for the ledger entry (e.g., `"ai_a1b2c3d4"`).
     * Mapped to `id VARCHAR(64) NOT NULL PRIMARY KEY`.
     */
    @Id
    @Column(name = "id", nullable = false, length = 64)
    private String id;

    /**
     * ID of the employee (`users.id`) who requested the optional AI assistance.
     * Mapped to `user_id VARCHAR(64) NOT NULL`.
     */
    @Column(name = "user_id", nullable = false, length = 64)
    private String userId;

    /**
     * Category of bounded AI action performed:
     *   - `INVITATION_DRAFT`: Drafting a 15-minute connection note from a story.
     *   - `STORY_POLISH`: Structuring an author's own story draft.
     *   - `UPDATE_SUMMARY`: Summarizing a published Official Update with source link.
     * Mapped to `assist_type VARCHAR(32) NOT NULL`.
     */
    @Column(name = "assist_type", nullable = false, length = 32)
    private String assistType; // INVITATION_DRAFT, STORY_POLISH, UPDATE_SUMMARY

    /**
     * ID of the content item (`content_items.id`) that grounded the AI request,
     * or `"draft"` when polishing unsaved text.
     * Mapped to `context_id VARCHAR(64) NOT NULL`.
     */
    @Column(name = "context_id", nullable = false, length = 64)
    private String contextId;

    /**
     * Estimated or actual input tokens sent to the AI model for this action.
     * Defaults to `1000` per Proposal Page 5 pilot sizing model.
     * Mapped to `input_tokens INT NOT NULL`.
     */
    @Column(name = "input_tokens", nullable = false)
    private int inputTokens = 1000;

    /**
     * Estimated or actual output tokens generated by the AI model for this action.
     * Defaults to `500` per Proposal Page 5 pilot sizing model.
     * Mapped to `output_tokens INT NOT NULL`.
     */
    @Column(name = "output_tokens", nullable = false)
    private int outputTokens = 500;

    /**
     * UTC timestamp recording when this AI assistance action was executed.
     * Mapped to `created_at TIMESTAMP WITH TIME ZONE NOT NULL`.
     */
    @Column(name = "created_at", nullable = false)
    private Instant createdAt = Instant.now();

    /**
     * Static factory method that constructs a ready-to-save `AiUsageLedgerEntity`
     * with a generated `"ai_"` UUID prefix and standard pilot token estimates (1,000 in / 500 out).
     *
     * @param userId     Authenticated user ID (`users.id`) triggering the action.
     * @param assistType Bounded assistance type (`INVITATION_DRAFT`, `STORY_POLISH`, `UPDATE_SUMMARY`).
     * @param contextId  Target content item ID (`content_items.id`) or `"draft"`.
     * @return A populated `AiUsageLedgerEntity` instance ready for `ledgerRepository.save(...)`.
     */
    public static AiUsageLedgerEntity create(String userId, String assistType, String contextId) {
        // Instantiate a new JPA entity.
        AiUsageLedgerEntity e = new AiUsageLedgerEntity();
        // Generate a compact unique ID prefixed with "ai_" followed by 8 hex chars of a random UUID.
        e.setId("ai_" + UUID.randomUUID().toString().substring(0, 8));
        // Bind the calling user's ID.
        e.setUserId(userId);
        // Bind the assistance category.
        e.setAssistType(assistType);
        // Bind the grounding content item ID (or "draft").
        e.setContextId(contextId);
        // Record the standard 1,000 input token budget unit (Proposal Page 5).
        e.setInputTokens(1000);
        // Record the standard 500 output token budget unit (Proposal Page 5).
        e.setOutputTokens(500);
        // Stamp the current UTC instant.
        e.setCreatedAt(Instant.now());
        return e;
    }

    /** @return Primary key ID of this ledger row. */
    public String getId() { return id; }
    /** @param id Primary key ID to set. */
    public void setId(String id) { this.id = id; }

    /** @return User ID of the employee who invoked AI assistance. */
    public String getUserId() { return userId; }
    /** @param userId User ID to set. */
    public void setUserId(String userId) { this.userId = userId; }

    /** @return Bounded assistance type (`INVITATION_DRAFT`, `STORY_POLISH`, `UPDATE_SUMMARY`). */
    public String getAssistType() { return assistType; }
    /** @param assistType Assistance type to set. */
    public void setAssistType(String assistType) { this.assistType = assistType; }

    /** @return Context content item ID or `"draft"`. */
    public String getContextId() { return contextId; }
    /** @param contextId Context content item ID to set. */
    public void setContextId(String contextId) { this.contextId = contextId; }

    /** @return Input token count recorded for this action. */
    public int getInputTokens() { return inputTokens; }
    /** @param inputTokens Input token count to set. */
    public void setInputTokens(int inputTokens) { this.inputTokens = inputTokens; }

    /** @return Output token count recorded for this action. */
    public int getOutputTokens() { return outputTokens; }
    /** @param outputTokens Output token count to set. */
    public void setOutputTokens(int outputTokens) { this.outputTokens = outputTokens; }

    /** @return UTC timestamp when the action occurred. */
    public Instant getCreatedAt() { return createdAt; }
    /** @param createdAt UTC timestamp to set. */
    public void setCreatedAt(Instant createdAt) { this.createdAt = createdAt; }
}
